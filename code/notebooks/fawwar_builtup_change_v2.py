"""## 7. Features and classification
**Default: K-means** with 10 classes on all dates together, then you choose the built-up classes (step 8).

**Optional, more accurate: Random Forest.** In QGIS create a point layer `train.gpkg` with an integer field `built` (1 = roof / paved, 0 = anything else). Put ~40 points of each kind **only on places that did NOT change** between the dates (so one label is valid for both images), include greenhouses, bright bare limestone, fields and trees as 0. Upload it and set `TRAIN_FILE = 'train.gpkg'`.
"""

def features(img):
    R, G, B = img[..., 0], img[..., 1], img[..., 2]
    br = (R + G + B) / 3
    exg = 2 * G - R - B
    mx, mn = img.max(-1), img.min(-1)
    sat = (mx - mn) / (mx + 1e-6)
    b0 = np.nan_to_num(br)
    tex = []
    for w in (3, 7):                                     # fine and coarse texture
        m1 = ndimage.uniform_filter(b0, w); m2 = ndimage.uniform_filter(b0 ** 2, w)
        tex.append(np.sqrt(np.clip(m2 - m1 ** 2, 0, None)))
    return np.stack([R, G, B, br, exg, sat, *tex], -1).astype('float32')

