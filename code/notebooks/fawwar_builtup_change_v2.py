"""## 5. Co-registration
Estimates the shift between the images from edge structure (robust to illumination) and moves the later image(s) onto the reference image. A shift of ~1–3 m is typical for Wayback imagery.

Note: this corrects a **global shift** only. Tall buildings still lean differently when the two images were taken from different angles (parallax) – the positional tolerance in step 9 handles that.
"""

def edges(img):
    br = np.nan_to_num(np.nanmean(img, -1), nan=float(np.nanmean(img)))
    return np.hypot(ndimage.sobel(br, 0), ndimage.sobel(br, 1))

if COREGISTER:
    rws, cls = np.where(common)
    r0, r1, c0, c1 = rws.min(), rws.max() + 1, cls.min(), cls.max() + 1
    ref_e = edges(imgs[REF][r0:r1, c0:c1])
    for d in dates:
        if d == REF:
            continue
        shift, err, _ = phase_cross_correlation(ref_e, edges(imgs[d][r0:r1, c0:c1]), upsample_factor=10)
        dy, dx = shift
        dist = np.hypot(dy, dx) * RES
        print(f'{d}: shift dy={dy * RES:+.2f} m, dx={dx * RES:+.2f} m (total {dist:.2f} m)')
        if dist > MAX_SHIFT_M:
            print('  -> larger than MAX_SHIFT_M, not applied')
            continue
        for b in range(3):
            imgs[d][..., b] = ndimage.shift(imgs[d][..., b], (dy, dx), order=1, mode='constant', cval=np.nan)
        valids[d] = ndimage.shift(valids[d].astype('float32'), (dy, dx), order=0, mode='constant', cval=0) > 0.5
        valids[d] &= ~np.isnan(imgs[d]).any(-1)
    common = update_common()
