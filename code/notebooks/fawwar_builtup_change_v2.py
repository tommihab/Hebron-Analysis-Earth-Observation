"""## 9. Clean built-up masks and detect change robustly
1. Vegetation (ExG > `VEG_EXG`) is never built-up
2. 3×3 majority filter, then morphological closing (fills small gaps in roofs) and opening (removes specks), then small patches removed
3. **new** = built-up on the later date with **no** built-up within `TOL_M` on the earlier date (and vice versa for **lost**)
4. Shadow pixels on either date are excluded from change
5. Optional spectral check: colour/texture must also change clearly
6. Change patches must be compact (opening with `CHANGE_OPEN_M`) and ≥ `MIN_CHANGE_M2`
"""

raw_built = {d: np.isin(labels[d], BUILT_CLUSTERS) & common & ~road_mask for d in dates}
def px(m):
    return max(1, int(round(m / RES)))

def remove_small(mask, min_m2):
    lab, n = ndimage.label(mask)
    if n == 0:
        return mask
    sizes = np.bincount(lab.ravel())
    keep = sizes >= max(1, int(min_m2 / PIX)); keep[0] = False
    return keep[lab]

se_clean = disk(px(CLEAN_M))
built, shadow = {}, {}
for d in dates:
    br = imgs[d].mean(-1)
    shadow[d] = common & (br <= np.nanpercentile(br[common], SHADOW_PCT))
    m = raw_built[d] & common & ~(feats[d][..., 4] > VEG_EXG)
    m = ndimage.median_filter(m.astype('uint8'), size=3).astype(bool)
    m = ndimage.binary_closing(m, se_clean)
    m = ndimage.binary_opening(m, se_clean)
    built[d] = remove_small(m, MIN_BUILT_M2) & common

tol = disk(px(TOL_M))
b0, b1 = built[first], built[last]
uncertain = shadow[first] | shadow[last]
sig = (mag > MAG_T) if SPECTRAL_CHECK else np.ones((H, W), bool)

def filt(m):
    m = m & sig & ~uncertain & common
    m = ndimage.binary_opening(m, disk(px(CHANGE_OPEN_M)))
    return remove_small(m, MIN_CHANGE_M2)

