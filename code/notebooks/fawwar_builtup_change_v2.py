"""## 2. Convert tile packages (.tpkx) to GeoTIFF"""

WM_ORIGIN = 20037508.342787
WM_RES0 = 156543.03392804097

def tpkx_to_geotiff(tpkx_path, out_tif, level=None):
    zf = zipfile.ZipFile(tpkx_path)
    pat = re.compile(r'L(\d+)/R([0-9a-fA-F]+)C([0-9a-fA-F]+)\.bundle$')
    bundles = {}
    for n in zf.namelist():
        m = pat.search(n)
        if m:
            bundles.setdefault(int(m.group(1)), []).append((n, int(m.group(2), 16), int(m.group(3), 16)))
    if not bundles:
        raise ValueError(f'No .bundle tiles found in {tpkx_path}')
    origin_x, origin_y, tile_size, packet, res_by_level, wkid = -WM_ORIGIN, WM_ORIGIN, 256, 128, {}, 3857
    roots = [n for n in zf.namelist() if n.lower().endswith('root.json')]
    if roots:
        root = json.loads(zf.read(roots[0]))
        info = root.get('tileInfo', {})
        o = info.get('origin', {})
        origin_x, origin_y = o.get('x', origin_x), o.get('y', origin_y)
        tile_size = info.get('rows', tile_size)
        res_by_level = {l['level']: l['resolution'] for l in info.get('lods', [])}
        sr = info.get('spatialReference', {})
        wkid = sr.get('latestWkid') or sr.get('wkid') or wkid
        packet = root.get('storageInfo', {}).get('packetSize', packet)
    level = max(bundles) if level is None else level
    res = res_by_level.get(level, WM_RES0 / 2 ** level)
    tiles = {}
    for name, brow, bcol in bundles[level]:
        data = zf.read(name)
        idx = np.frombuffer(data[64:64 + 8 * packet * packet], dtype='<u8')
        for k in np.nonzero(idx >> np.uint64(40))[0]:
            off = int(idx[k] & np.uint64((1 << 40) - 1)); size = int(idx[k] >> np.uint64(40))
            tiles[(brow + k // packet, bcol + k % packet)] = data[off:off + size]
    rows = [r for r, _ in tiles]; cols = [c for _, c in tiles]
    r0, r1, c0, c1 = min(rows), max(rows), min(cols), max(cols)
    mosaic = np.zeros(((r1 - r0 + 1) * tile_size, (c1 - c0 + 1) * tile_size, 3), dtype='uint8')
    for (r, c), b in tiles.items():
        im = np.asarray(Image.open(io.BytesIO(b)).convert('RGB'))
        y, x = (r - r0) * tile_size, (c - c0) * tile_size
        mosaic[y:y + im.shape[0], x:x + im.shape[1]] = im
    crs = 'EPSG:3857' if wkid in (102100, 102113, 900913, 3857) else f'EPSG:{wkid}'
    transform = from_origin(origin_x + c0 * tile_size * res, origin_y - r0 * tile_size * res, res, res)
    with rasterio.open(out_tif, 'w', driver='GTiff', height=mosaic.shape[0], width=mosaic.shape[1], count=3,
                       dtype='uint8', crs=crs, transform=transform, nodata=0, compress='deflate', tiled=True) as dst:
        dst.write(np.moveaxis(mosaic, -1, 0))
    print(f'{os.path.basename(tpkx_path)}: level {level}, {len(tiles)} tiles, {res:.2f} m/px -> {out_tif}')
    return out_tif

