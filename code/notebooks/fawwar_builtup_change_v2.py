def load(path):
    out = np.full((3, H, W), np.nan, dtype='float32')
    with rasterio.open(path) as src:
        for b in range(3):
            reproject(rasterio.band(src, min(b + 1, src.count)), out[b],
                      src_transform=src.transform, src_crs=src.crs, src_nodata=src.nodata,
                      dst_transform=GT, dst_crs=TARGET_CRS, dst_nodata=np.nan, resampling=Resampling.average)
    img = np.moveaxis(out, 0, -1)
    return img, ~np.isnan(img).any(-1) & (np.nansum(img, -1) > 0)

